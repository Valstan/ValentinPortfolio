// Русская грамматика для чисел и перечислений, которые считаются из данных.
//
// Зачем отдельный файл: на витрине набранное руками число живёт ровно до следующей
// правки каталога и молча становится ложью — «Шесть формулировок задач» над списком
// из семи, «восемь вопросов» над девятью. Лечение то же, что у чисел первого экрана:
// считать из данных. Но по-русски «6 вопрос» и «1 вопросов» не напишешь, поэтому
// счёт из данных требует согласования — оно здесь.
//
// Прописью, а не цифрами, потому что так эти фразы и написаны на витрине: «Шесть
// формулировок задач», а не «6 формулировок задач».

/** Род существительного — от него зависят «один/одна» и «два/две». */
export type Gender = 'm' | 'f';

/** Формы при 1, 2 и 5: «вопрос», «вопроса», «вопросов». */
export type PluralForms = readonly [one: string, few: string, many: string];

/**
 * Форма существительного при числе `n`.
 *
 * Правило школьное, но с двумя исключениями, на которых обычно и ломаются:
 * 11–14 идут по форме «пяти» (одиннадцать вопросов, а не «одиннадцать вопрос»),
 * и считается остаток от деления на 100, а не на 10.
 */
export function plural(n: number, forms: PluralForms): string {
  const hundreds = Math.abs(n) % 100;
  if (hundreds > 10 && hundreds < 20) return forms[2];
  const units = hundreds % 10;
  if (units === 1) return forms[0];
  if (units >= 2 && units <= 4) return forms[1];
  return forms[2];
}

const WORDS = [
  'ноль',
  'один',
  'два',
  'три',
  'четыре',
  'пять',
  'шесть',
  'семь',
  'восемь',
  'девять',
  'десять',
  'одиннадцать',
  'двенадцать',
  'тринадцать',
  'четырнадцать',
  'пятнадцать',
  'шестнадцать',
  'семнадцать',
  'восемнадцать',
  'девятнадцать',
  'двадцать',
];

/**
 * Числительное словами. За двадцатью — цифрами: столько пунктов прозой уже не
 * перечисляют, и если витрина туда доберётся, фразу всё равно придётся переписать.
 */
export function numeral(n: number, gender: Gender = 'm'): string {
  if (!Number.isInteger(n) || n < 0 || n >= WORDS.length) return String(n);
  if (n === 1) return gender === 'f' ? 'одна' : 'один';
  if (n === 2) return gender === 'f' ? 'две' : 'два';
  return WORDS[n];
}

/** «шесть вопросов», «одна формулировка задач», «21 вопрос». */
export function countPhrase(n: number, forms: PluralForms, gender: Gender = 'm'): string {
  return `${numeral(n, gender)} ${plural(n, forms)}`;
}

/** Первая буква прописной — для начала предложения. */
export function capitalize(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/** «А», «А и Б», «А, Б и В». */
export function listRu(items: string[]): string {
  if (items.length < 2) return items.join('');
  return `${items.slice(0, -1).join(', ')} и ${items[items.length - 1]}`;
}

/**
 * Самопроверка на импорте модуля, то есть при `next build`, то есть на PR-гейте.
 *
 * Зачем она здесь, а не «и так очевидно»: на этот файл теперь опираются пять фраз
 * витрины, и ошибка в согласовании не упадёт — она просто напечатает «одиннадцать
 * вопрос» на живой странице. Отдельного прогона тестов у проекта нет, а сборка есть,
 * поэтому проверка живёт в сборке. Случаи взяты те, на которых правило и ломается:
 * 11–14 (ведут себя как «пять», хотя кончаются на 1–4) и род при 1 и 2.
 */
(function assertRu() {
  const forms = ['вопрос', 'вопроса', 'вопросов'] as const;
  const expected: Array<[number, string]> = [
    [0, 'ноль вопросов'],
    [1, 'один вопрос'],
    [2, 'два вопроса'],
    [4, 'четыре вопроса'],
    [5, 'пять вопросов'],
    [8, 'восемь вопросов'],
    [11, 'одиннадцать вопросов'],
    [12, 'двенадцать вопросов'],
    [14, 'четырнадцать вопросов'],
    [15, 'пятнадцать вопросов'],
    [20, 'двадцать вопросов'],
    [21, '21 вопрос'],
    [22, '22 вопроса'],
    [25, '25 вопросов'],
    [111, '111 вопросов'],
  ];
  for (const [n, want] of expected) {
    const got = countPhrase(n, forms);
    if (got !== want) {
      throw new Error(`ru: countPhrase(${n}) дал «${got}», а по-русски «${want}»`);
    }
  }

  const feminine: Array<[number, string]> = [
    [1, 'одна задача'],
    [2, 'две задачи'],
    [5, 'пять задач'],
  ];
  for (const [n, want] of feminine) {
    const got = countPhrase(n, ['задача', 'задачи', 'задач'], 'f');
    if (got !== want) {
      throw new Error(`ru: countPhrase(${n}, 'f') дал «${got}», а по-русски «${want}»`);
    }
  }

  const lists: Array<[string[], string]> = [
    [[], ''],
    [['А'], 'А'],
    [['А', 'Б'], 'А и Б'],
    [['А', 'Б', 'В'], 'А, Б и В'],
  ];
  for (const [items, want] of lists) {
    const got = listRu(items);
    if (got !== want) {
      throw new Error(`ru: listRu([${items.join('|')}]) дал «${got}», ожидалось «${want}»`);
    }
  }
})();
