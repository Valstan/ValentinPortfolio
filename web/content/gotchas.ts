// Журнал грабель — разборы производственных ошибок, пережитых на этих системах.
//
// Зачем раздел вообще: остальной сайт отвечает на вопрос «что я сделал». Этот —
// на вопрос «что я знаю такого, чего нет в документации». Такой ответ невозможно
// придумать, не поработав: у каждой записи есть версия инструмента, симптом и
// строка, которой это воспроизводится.
//
// ⛔ ГРАНИЦА ПУБЛИКАЦИИ (D-038). Сюда попадает только то, что воспроизводится на
// чужой машине из открытых данных: имена и версии инструментов, поведение
// фреймворков, ошибки в собственных рассуждениях. НЕ попадает ничего про
// раскладку эксплуатации: имена и адреса серверов, порты, состав жильцов, откуда
// и куда ходят проверки, географию инфраструктуры. Правило простое: если запись
// помогает атакующему построить карту — её здесь нет, какой бы поучительной она
// ни была.

export type Gotcha = {
  /** URL-сегмент: /grabli/<slug>/ — один адрес на один симптом. */
  slug: string;
  /** Симптом словами того, кто на это напоролся: он же h1 и поисковый запрос. */
  symptom: string;
  /** Где это случается: инструмент и версия. Без версии запись бесполезна. */
  where: string;
  /** Почему так происходит — механизм, а не пересказ симптома. */
  cause: string;
  /** Что делать. */
  fix: string;
  /** Как убедиться, что дело именно в этом. Проверка, а не совет «посмотрите внимательнее». */
  check: string;
  /** Дата, когда напоролись. */
  metAt: string;
  /** Чем это кончилось бы, если не заметить. */
  cost: string;
};

