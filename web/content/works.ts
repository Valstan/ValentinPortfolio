export type WorkStatus = 'в проде' | 'каркас в проде' | 'внутренний сервис';

/**
 * Факт с датой замера. Правило витрины: **факт без даты замера на сайт не попадает** —
 * иначе «523 коммита» через полгода превращается в неправду, которую никто не заметил.
 *
 * `verify: 'external'` — читатель может проверить сам, не спрашивая меня.
 * `verify: 'measured'` — мой замер, проверить снаружи нельзя. Разделение показывается явно.
 */
export type Fact = {
  claim: string;
  /** ISO-дата замера. */
  asOf: string;
  verify: 'external' | 'measured';
};

export type Work = {
  /** URL-сегмент: /raboty/<slug>/ */
  slug: string;
  title: string;
  /** Одна строка курсивом под заголовком — что это за система. */
  tagline: string;
  /** Группа на витрине. */
  group: 'flagship' | 'events' | 'services' | 'wip';
  status: WorkStatus;
  /** Публичный продуктовый URL в юникоде — для показа. В href всегда прогоняется через absoluteUrl-хелпер. */
  prodUrl?: string;
  /** Как показать домен человеку. */
  prodLabel?: string;
  /** 2–4 предложения: что система даёт заказчику, без жаргона. */
  whatItGives: string;
  /** Технические решения — по одному пункту на решение. */
  underTheHood: string[];
  stack: string;
  /** Проверяемые факты — то, что цитируют LLM и во что верит заказчик. */
  facts: Fact[];
  plans: string[];
  /** Каталог со скриншотами в /shots/<screenshotDir>/, если снимки есть. */
  screenshotDir?: string;
  /** Почему скриншотов нет — показывается вместо них, честно. */
  noScreenshotReason?: string;
};

