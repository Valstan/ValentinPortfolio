/**
 * Состав конструктора одной строкой: «что нужно, кто будет пользоваться, …».
 *
 * Одно место на три текста — описание `/tehzadanie/`, `llms.txt` и подводку на
 * `/zadachi/`. Число вопросов там же считается из длины этого массива (`lib/ru.ts`),
 * поэтому «восемь вопросов» и перечисление из восьми пунктов не могут разойтись
 * ни между собой, ни с самим конструктором.
 */
export const BRIEF_TOPICS: string = BRIEF_QUESTIONS.map((question) => question.topic).join(', ');

/**
 * Ссылка на конструктор с уже отмеченным первым ответом.
 *
 * Со страницы задачи известно, зачем человек пришёл, — переспрашивать его об этом
 * первым же вопросом невежливо. Маппинг не отдельный: берём тот вариант, который
 * и так ссылается на эту задачу, поэтому второй копии соответствий не возникает.
 */
export function briefHrefForTask(taskSlug: string): string {
  const need = BRIEF_QUESTIONS.find((question) => question.id === 'need');
  const option = need?.options.find((o) => (o.taskSlugs ?? []).includes(taskSlug));
  return option ? `/tehzadanie/#tz=need:${option.id}` : '/tehzadanie/';
}

/**
 * Целостность проверяется на импорте модуля, то есть при `next build`, то есть
 * на PR-гейте.
 *
 * Зачем: варианты ссылаются на задачи и работы по слагу. Работу снимают с витрины
 * (как Калининскую ЦКС 04.09) — и ссылка молча превращается в пустоту: раздел
 * «где похожее уже работает» просто недосчитывается пункта, и никто этого не
 * замечает. Пусть лучше не собирается сборка.
 */
(function assertBrief() {
  const seenQuestions = new Set<string>();

  for (const question of BRIEF_QUESTIONS) {
    if (seenQuestions.has(question.id)) {
      throw new Error(`brief: дублирующийся id вопроса «${question.id}»`);
    }
    seenQuestions.add(question.id);

    // Без темы вопрос выпадет из перечисления состава (`BRIEF_TOPICS`) молча —
    // строка просто станет короче, и никто не заметит.
    if (!question.topic.trim()) {
      throw new Error(`brief: у вопроса «${question.id}» пустая тема — он выпадет из перечисления состава конструктора`);
    }
    if (question.topic.includes(',')) {
      throw new Error(
        `brief: тема вопроса «${question.id}» содержит запятую — перечисление состава склеивается запятыми и распадётся на лишние пункты`,
      );
    }

    const seenOptions = new Set<string>();
    for (const option of question.options) {
      if (seenOptions.has(option.id)) {
        throw new Error(`brief: дублирующийся id варианта «${option.id}» в «${question.id}»`);
      }
      seenOptions.add(option.id);

      for (const slug of option.taskSlugs ?? []) {
        if (!taskBySlug(slug)) {
          throw new Error(`brief: вариант «${question.id}:${option.id}» ссылается на несуществующую задачу «${slug}»`);
        }
      }
      for (const slug of option.workSlugs ?? []) {
        if (!workBySlug(slug)) {
          throw new Error(
            `brief: вариант «${question.id}:${option.id}» ссылается на работу «${slug}», которой нет на витрине (снята или переименована)`,
          );
        }
      }
    }
  }
})();
