export type WorkStatus = 'в проде' | 'каркас в проде' | 'внутренний сервис';

/**
 * Факт с датой замера. Правило витрины: **факт без даты замера на сайт не попадает** —
 * иначе «523 коммита» через полгода превращается в неправду, которую никто не заметил.
 *
 * `verify: 'external'` — читатель может проверить сам, не спрашивая меня.
 * `verify: 'measured'` — мой замер, проверить снаружи нельзя. Разделение показывается явно.
 */
export type Fact = {
  claim: string;
  /** ISO-дата замера. */
  asOf: string;
  verify: 'external' | 'measured';
};

export type Shot = {
  /** Имя файла внутри /shots/<dir>/ */
  file: string;
  caption: string;
  /** Пропорция рамки: экран компьютера или телефона. */
  ratio: 'wide' | 'phone';
  /** Адрес в шапке рамки. У настольной программы адреса нет — шапка не рисуется. */
  address?: string;
};

/** Стандартная пара снимков сайта: тем же кадром снят каждый прод (метод #079). */
function webShots(dir: string, address: string): { dir: string; items: Shot[] } {
  return {
    dir,
    items: [
      { file: 'desktop.jpg', caption: 'Как выглядит на компьютере', ratio: 'wide', address },
      { file: 'mobile.jpg', caption: 'И на телефоне', ratio: 'phone' },
    ],
  };
}

export type Work = {
  /** URL-сегмент: /raboty/<slug>/ */
  slug: string;
  title: string;
  /** Одна строка курсивом под заголовком — что это за система. */
  tagline: string;
  /** Группа на витрине. */
  group: 'flagship' | 'events' | 'services';
  /**
   * Тип сущности для JSON-LD. По умолчанию `CreativeWork` — им размечается всё, чему
   * не подобрано точнее. Настольная программа и устанавливаемое приложение — не
   * «произведение», и модель, отвечая на вопрос «что это за система», разбирает их
   * по-разному.
   */
  schemaType?: 'CreativeWork' | 'WebSite' | 'SoftwareApplication' | 'WebApplication';
  /** Временно скрыто из показа, данные и снимки остаются на месте (обратное включение — снять флаг). */
  hidden?: boolean;
  status: WorkStatus;
  /** Публичный продуктовый URL в юникоде — для показа. В href всегда прогоняется через absoluteUrl-хелпер. */
  prodUrl?: string;
  /** Как показать домен человеку. */
  prodLabel?: string;
  /** 2–4 предложения: что система даёт заказчику, без жаргона. */
  whatItGives: string;
  /** Технические решения — по одному пункту на решение. */
  underTheHood: string[];
  stack: string;
  /** Проверяемые факты — то, что цитируют LLM и во что верит заказчик. */
  facts: Fact[];
  plans: string[];
  /**
   * Снимки в /shots/<dir>/. Список явный, а не пара «десктоп + мобайл»:
   * у настольной программы мобильной версии не бывает, зато бывает два рабочих экрана.
   */
  shots?: { dir: string; items: Shot[] };
  /** Оговорка под снимками — например, что съёмка на обезличенных данных. */
  shotsNote?: string;
  /** Почему скриншотов нет — показывается вместо них, честно. */
  noScreenshotReason?: string;
};

